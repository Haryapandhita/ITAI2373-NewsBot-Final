"""Report generation and export (Markdown, HTML, JSON, CSV)."""

from __future__ import annotations

import html
import json
from datetime import datetime
from pathlib import Path
from typing import Dict, Iterable, List, Optional

import pandas as pd

from src.utils.evaluation import to_jsonable


def article_report_markdown(analysis: Dict, title: str = "Article analysis") -> str:
    """Readable Markdown report for one ``NewsBot2.analyze_article`` result."""
    c, s = analysis["classification"], analysis["sentiment"]
    lines = [f"# {title}", "", f"*Generated by NewsBot 2.0 on {datetime.now():%Y-%m-%d %H:%M}*", "",
             "## Overview", "",
             f"- **Language:** {analysis['language']['name']} (confidence {analysis['language']['confidence']:.0%})",
             f"- **Category:** {c['label']} ({c['confidence']:.0%})"
             + (f" – secondary: {', '.join(c['secondary_labels'])}" if c["secondary_labels"] else ""),
             f"- **Needs human review:** {'yes' if c['needs_review'] else 'no'}",
             f"- **Sentiment:** {s['label']} ({s['score']:+.2f})", ""]
    if analysis.get("summary"):
        lines += ["## Summary", "", analysis["summary"]["summary"], ""]
    if analysis.get("headlines"):
        lines += ["## Suggested headlines", ""] + [f"- *{k}:* {v}" for k, v in analysis["headlines"].items()] + [""]
    if analysis.get("entities"):
        ents = pd.DataFrame(analysis["entities"]).drop_duplicates("canonical")
        lines += ["## Entities", ""] + [f"- {r.canonical} ({r.label})" for r in ents.head(15).itertuples()] + [""]
    if analysis.get("relations"):
        lines += ["## Relations", ""] + [f"- {r['source']} —{r['relation']}→ {r['target']}" for r in analysis["relations"][:10]] + [""]
    if analysis.get("topics"):
        lines += ["## Topics", ""] + [f"- {t['label']} ({t['weight']:.0%})" for t in analysis["topics"]] + [""]
    enh = analysis.get("enhancements") or {}
    if enh.get("entity_background"):
        lines += ["## Background", ""] + [f"- **{b['entity']}** – {b['mentions_in_corpus']} articles, mostly {b['mostly_in']}; "
                                         f"often with {b['often_with']}" for b in enh["entity_background"]] + [""]
    if enh.get("tone_context"):
        lines += [f"*{enh['tone_context']}*", ""]
    return "\n".join(lines)


def markdown_to_html(md: str, title: str = "NewsBot report") -> str:
    """Very small Markdown -> HTML converter (headings, bullets, emphasis)."""
    out = [f"<html><head><meta charset='utf-8'><title>{html.escape(title)}</title>",
           "<style>body{font-family:system-ui,Arial;max-width:860px;margin:40px auto;line-height:1.5;color:#1e293b}"
           "h1{color:#1d4ed8}h2{border-bottom:1px solid #e2e8f0;padding-bottom:4px}</style></head><body>"]
    in_list = False
    for line in md.splitlines():
        esc = html.escape(line)
        esc = __import__("re").sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", esc)
        esc = __import__("re").sub(r"\*(.+?)\*", r"<i>\1</i>", esc)
        if line.startswith("- "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{esc[2:]}</li>")
            continue
        if in_list:
            out.append("</ul>")
            in_list = False
        if line.startswith("## "):
            out.append(f"<h2>{esc[3:]}</h2>")
        elif line.startswith("# "):
            out.append(f"<h1>{esc[2:]}</h1>")
        elif line.strip():
            out.append(f"<p>{esc}</p>")
    if in_list:
        out.append("</ul>")
    out.append("</body></html>")
    return "\n".join(out)


def export_results(data, path: Path, fmt: Optional[str] = None) -> Path:
    """
    Save ``data`` (DataFrame, dict or Markdown string) as csv / json /
    markdown / html, chosen from ``fmt`` or the file extension.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fmt = (fmt or path.suffix.lstrip(".")).lower()
    if fmt == "csv":
        pd.DataFrame(data).to_csv(path, index=False)
    elif fmt == "json":
        payload = data.to_dict(orient="records") if isinstance(data, pd.DataFrame) else data
        path.write_text(json.dumps(to_jsonable(payload), indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    elif fmt in ("md", "markdown"):
        path.write_text(data if isinstance(data, str) else pd.DataFrame(data).to_markdown(index=False), encoding="utf-8")
    elif fmt == "html":
        body = data if isinstance(data, str) else pd.DataFrame(data).to_markdown(index=False)
        path.write_text(markdown_to_html(body), encoding="utf-8")
    else:
        raise ValueError(f"Unsupported export format: {fmt}")
    return path
